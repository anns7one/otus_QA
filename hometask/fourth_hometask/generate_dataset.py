class GenerationStopped(Exception):
    """Пользователь прервал генерацию командой exit."""

def ask_model(prompt: str, context: list[int] | None = None) -> tuple[str, list[int]]:
    """Отправляет запрос в Ollama и возвращает ответ (context для продолжения диалога)."""
    body = {
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {
            "temperature": 0.4,
            "num_predict": 350,
        },
    }
    if context is not None:
        body["context"] = context

    payload = json.dumps(body).encode("utf-8")
    request = urllib.request.Request(
        OLLAMA_URL,
        data=payload,
        headers={"Content-Type": "application/json"},
    )

    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            data = json.loads(response.read().decode("utf-8"))
            return data["response"], data["context"]
    except urllib.error.URLError as error:
        print("Не удалось достучаться до Ollama в контейнере.")
        print(f"  Причина: {error}")
        print("  Проверьте, что контейнер запущен командой docker ps")
        sys.exit(1)


def build_prompt(topic: str, source: str) -> str:
    return (
        f"Ниже — фрагмент официального стандарта ISTQB Foundation Level Syllabus v4.0, "
        f"тема «{topic}»:\n\n"
        f"{source}\n\n"
        f"Перескажи этот фрагмент своими словами, текстом объёмом около 500 символов. "
        f"Используй ТОЛЬКО факты из фрагмента выше, ничего не добавляй от себя и не "
        f"придумывай. Пиши только сам текст, без заголовка, без вступления и без "
        f"markdown-разметки."
    )

def confirm_or_refine(topic: str, source: str) -> str:
    """Генерирует текст по теме; даёт пользователю принять или скорректировать генерацию."""
    prompt = build_prompt(topic, source)
    context = None

    while True:
        text, context = ask_model(prompt, context)
        text = text.strip()
        print(f"\n{text}\n")

        answer = input("Устраивает текст? (да = y / нет = n): ").strip().lower()
        if answer in ("exit", "выход", "stop"):
            raise GenerationStopped
        
        if answer in ("", "да", "y", "yes"):
            return text

        prompt = input("Что поправить? (опиши, в какую сторону скорректировать): ").strip()

def save_dataset(documents: list[dict], output_path: Path) -> None:
    """Перезаписывает файл датасета текущим списком документов."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(documents, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

def dataset_dir_for(n: int) -> Path:
    """Папка n-го по счёту датасета: 1 -> dataset, 2 -> dataset_2, 3 -> dataset_3, ..."""
    return HERE / "dataset" if n == 1 else HERE / f"dataset_{n}"


def latest_dataset_number() -> int:
    """Номер самого свежего существующего датасета (1, если ни одного ещё нет)."""
    n = 1
    while (dataset_dir_for(n + 1) / "knowledge_base.json").exists():
        n += 1
    return n
   

def load_existing_dataset(output_path: Path) -> list[dict]:
    """Загружает уже сохранённый датасет, если он есть — для возобновления генерации."""
    if not output_path.exists():
        return []
    return json.loads(output_path.read_text(encoding="utf-8"))

def main() -> None:
    n = latest_dataset_number()
    output_path = dataset_dir_for(n) / "knowledge_base.json"
    documents = load_existing_dataset(output_path)

    if documents and len(documents) == len(TOPICS):
        n += 1
        output_path = dataset_dir_for(n) / "knowledge_base.json"
        print(f"Текущий датасет уже полный (10/10). Новая генерация пойдёт в {output_path.relative_to(HERE)}")
        documents = []

    done_titles = {doc["title"] for doc in documents}

    if documents:
        print(f"Найден существующий датасет: {len(documents)}/{len(TOPICS)} тем уже сгенерировано.")

    try:
        for i, (topic, source) in enumerate(TOPICS, start=1):
            if topic in done_titles:
                answer = input(
                    f"[{i}/{len(TOPICS)}] «{topic}» уже есть в датасете. "
                    f"Перегенерировать? (да/нет, Enter = нет — оставить как есть): "
                ).strip().lower()
                if answer not in ("да", "y", "yes"):
                    continue
                documents = [doc for doc in documents if doc["title"] != topic]

            print(f"[{i}/{len(TOPICS)}] Генерирую текст: {topic}")
            text = confirm_or_refine(topic, source)
            documents.append({"id": i, "title": topic, "text": text})
            save_dataset(documents, output_path)
            print(f"Сохранено в {output_path.relative_to(HERE)} ({len(documents)}/{len(TOPICS)})")
    except GenerationStopped:
        print(f"\nГенерация прервана пользователем. Сохранено документов: {len(documents)}/{len(TOPICS)}")
        return

    print(f"\nГотово. Всего документов: {len(documents)}")


if __name__ == "__main__":
    main()