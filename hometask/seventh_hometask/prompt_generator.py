def build_prompt(requirement_text: str, artifact_type: str) -> str:
    spec = ARTIFACT_SPECS[artifact_type]
    return (
        f"{spec['role']}\n\n"
        f"Контекст (требование):\n{requirement_text}\n\n"
        f"Техника: {spec['technique']}\n\n"
        f"Формат: {spec['format']}\n\n"
        f"Ограничения: {spec['constraints']}"
    )


def load_requirement(path: str) -> str:
    return Path(path).read_text(encoding="utf-8")


def generate_all_prompts(requirement_path: str) -> dict[str, str]:
    requirement_text = load_requirement(requirement_path)
    return {artifact_type: build_prompt(requirement_text, artifact_type) for artifact_type in ARTIFACT_SPECS}
