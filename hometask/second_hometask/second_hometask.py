# Обучение нейросети
class Brain(nn.Module):

    def __init__(self, vocab_size: int):
        super().__init__()
        # Эмбеддинг: номер слова превращает в вектор из EMBED_DIM чисел.
        self.embedding = nn.Embedding(vocab_size, EMBED_DIM)

        # Механизм внимания: три взгляда на одно и то же слово
        self.query = nn.Linear(EMBED_DIM, EMBED_DIM)   # что я ищу
        self.key = nn.Linear(EMBED_DIM, EMBED_DIM)     # что я предлагаю
        self.value = nn.Linear(EMBED_DIM, EMBED_DIM)   # что я отдам

        # Выходной слой: вектор -> оценка для каждого слова словаря
        self.output = nn.Linear(EMBED_DIM, vocab_size)

    def forward(self, tokens):
        x = self.embedding(tokens)

        q, k, v = self.query(x), self.key(x), self.value(x)

        # Насколько каждое слово важно для каждого другого
        scores = q @ k.transpose(-2, -1) / (EMBED_DIM ** 0.5)

        # Запрещаем смотреть вперёд: иначе модель спишет правильный ответ
        length = tokens.size(1)
        mask = torch.triu(torch.ones(length, length), diagonal=1).bool()
        scores = scores.masked_fill(mask, float("-inf"))

        # softmax превращает оценки в веса
        attention = F.softmax(scores, dim=-1) @ v

        return self.output(attention)


# Модель
class TestLLM:

    def __init__(self):
        self.train_data: list[str] = []
        self.word_to_idx: dict[str, int] = {}
        self.idx_to_word: list[str] = []
        self.brain: Brain | None = None

    def train(self, data: list[str]) -> None:
        """Обучение нейросети: 15 эпох с выводом loss на каждой."""
        self.train_data = data

        # 1. Словарь: каждому уникальному слову — свой номер
        words = sorted({word for phrase in data for word in phrase.split()})
        self.idx_to_word = words
        self.word_to_idx = {word: i for i, word in enumerate(words)}

        # 2. Обучающие примеры: окно из SEQ_LEN слов -> те же слова со сдвигом.
        #    Модель учится: видя слова 1..N, предсказать слова 2..N+1
        stream = [self.word_to_idx[w] for phrase in data for w in phrase.split()]
        inputs, targets = [], []
        for i in range(len(stream) - SEQ_LEN):
            inputs.append(stream[i : i + SEQ_LEN])
            targets.append(stream[i + 1 : i + SEQ_LEN + 1])
        inputs = torch.tensor(inputs)
        targets = torch.tensor(targets)

        # 3. Создаём нейросеть теперь, когда знаем размер словаря
        torch.manual_seed(42)                      # чтобы результат повторялся
        self.brain = Brain(len(words))

        criterion = nn.CrossEntropyLoss()          # измеряет ошибку модели
        optimizer = torch.optim.Adam(self.brain.parameters(), lr=LEARNING_RATE)

        print(f"Словарь: {len(words)} слов | Примеров: {len(inputs)} | "
              f"Параметров: {sum(p.numel() for p in self.brain.parameters()):,}")
        print(f"Обучение, {EPOCHS} эпох:")

        # 4. Собственно обучение
        for epoch in range(1, EPOCHS + 1):
            optimizer.zero_grad()                  # забыть прошлые поправки
            predictions = self.brain(inputs)       # что думает модель

            # CrossEntropyLoss ждёт плоские списки, поэтому reshape
            loss = criterion(
                predictions.reshape(-1, len(words)),
                targets.reshape(-1),
            )

            loss.backward()                        # куда двигать веса
            optimizer.step()                       # двигаем

            print(f"  эпоха {epoch:2d}/{EPOCHS}  loss = {loss.item():.4f}")

    def predict_next_word(self, start_word: str) -> str:
        """Тот же метод, что в ДЗ-1, но отвечает нейросеть."""
        if self.brain is None:
            return "Модель не обучена."
        if start_word not in self.word_to_idx:
            return "Слово не найдено в обучающей выборке."

        tokens = torch.tensor([[self.word_to_idx[start_word]]])
        with torch.no_grad():
            predictions = self.brain(tokens)
        best = int(predictions[0, -1].argmax())
        return self.idx_to_word[best]

    def generate(self, start_text: str, length: int = 40) -> str:
        """Генерация цепочки слов: предсказали, дописали, повторили."""
        if self.brain is None:
            return "Модель не обучена."

        ids = [self.word_to_idx[w] for w in start_text.split()
               if w in self.word_to_idx]
        if not ids:
            return "Слова начальной фразы отсутствуют в словаре."

        while len(ids) < length:
            context = torch.tensor([ids[-SEQ_LEN:]])
            with torch.no_grad():
                predictions = self.brain(context)
            # Берём случайное слово с учётом вероятностей, а не всегда самое
            # вероятное — иначе модель зацикливается на одном слове
            probs = F.softmax(predictions[0, -1], dim=-1)
            ids.append(int(torch.multinomial(probs, 1)))

        return " ".join(self.idx_to_word[i] for i in ids)


# Шаг 1. Скачиваем страницу и разбираем её на части
def strip_tags(fragment: str) -> str:
    """Убирает HTML-теги, оставляя только текст."""
    fragment = fragment.replace("<!-- -->", " ")
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", fragment)).strip()


def fetch_page(url: str) -> str:
    """Скачивает страницу и собирает СТРУКТУРИРОВАННОЕ описание.

    Важный момент: если просто выбросить все теги, получится сплошная
    простыня текста, где меню, фильтры и карточки идут вперемешку. Модель
    на 3 млрд параметров в такой каше путается — например, принимает слово
    «Курс» (тип карточки) за название кнопки.

    Поэтому разбираем страницу на части: отдельно кнопки, отдельно фильтры,
    отдельно карточки с разложенными полями. Качество анализа примерно на
    70% определяется качеством входа.
    """
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    html = urllib.request.urlopen(request, timeout=30).read().decode("utf-8", "ignore")

    # Плоский текст нужен для поиска блока фильтров
    flat = strip_tags(re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", html,
                             flags=re.S | re.I))

    # Блок фильтров: от начала списка направлений до кнопки сброса
    found = re.search(r"(Направление .*?Очистить фильтры)", flat)
    filters_block = found.group(1) if found else "блок фильтров не найден"

    # Кнопки: берём текст тега <button>, отбрасывая иконки
    buttons: list[str] = []
    for raw in re.findall(r"<button[^>]*>(.*?)</button>", html, re.S):
        text = strip_tags(raw)
        if text and len(text) < 40 and text not in buttons:
            buttons.append(text)

    # Карточки курсов: раскладываем каждую на тип, бейдж, название, дату.
    # Всё, что идёт после заголовка блока рекомендаций, — не результаты каталога.
    recommendations_start = html.find("Вам также может быть интересно")
    catalog: list[str] = []
    recommended: list[str] = []

    for match in re.finditer(r'<a[^>]+href="(/lessons/[^"]+)"[^>]*>(.*?)</a>',
                             html, re.S):
        inner = match.group(2)
        title = re.search(r"<h\d[^>]*>(.*?)</h\d>", inner, re.S)
        if not title:
            continue  # это не карточка курса, а обычная ссылка меню

        kind = re.search(r"<p[^>]*>(Курс|Специализация)", inner)
        date = re.findall(r"<div[^>]*>([^<]*·[^<]*)</div>", inner)
        badge = re.search(r"(Успеть!|Скидка\s*[\d\s]+₽)", strip_tags(inner))

        line = (f"тип={kind.group(1) if kind else '?'} | "
                f"бейдж={badge.group(1).strip() if badge else 'нет'} | "
                f"название={strip_tags(title.group(1))} | "
                f"дата и срок={date[0].strip() if date else '?'}")

        is_recommendation = (recommendations_start != -1
                             and match.start() > recommendations_start)
        (recommended if is_recommendation else catalog).append(line)

    return "\n".join([
        f"АДРЕС: {url}",
        "",
        "БЛОК ФИЛЬТРОВ (левая колонка):",
        filters_block,
        "",
        "КНОПКИ НА СТРАНИЦЕ: " + ", ".join(buttons),
        "",
        f"КАРТОЧКИ В КАТАЛОГЕ ({len(catalog)} шт., показаны при первой загрузке):",
        *catalog,
        "",
        f"ОТДЕЛЬНЫЙ БЛОК «Вам также может быть интересно» ({len(recommended)} шт.) —",
        "это рекомендации, они НЕ подчиняются выбранному фильтру:",
        *recommended,
    ])


# Шаг 2. Запрос к нейросети
def ask_ollama(task: str, context: str = "") -> str:
    """Один запрос к llama3.2.

    Промпт по схеме из курса: Роль -> Контекст -> Задача -> Формат.
    """
    prompt = f"""Роль: ты senior QA-инженер. Пишешь по существу, без вступлений.

ЯЗЫК: пиши ТОЛЬКО по-русски, кириллицей. Не вставляй слова на английском,
испанском или любом другом языке. Исключение — названия из самой страницы
(Basic, Professional, Advanced, Data Science, GameDev) и обозначения
статусов PASSED и FAILED.

{context}

Задача: {task}

Формат: markdown на русском. Верни только сам документ, без фраз
вроде «Вот ваш документ»."""

    response = ollama.chat(
        model=OLLAMA_MODEL,
        messages=[{"role": "user", "content": prompt}],
        options={"temperature": 0.2},  # документация, а не творчество
    )
    return response["message"]["content"].strip()


