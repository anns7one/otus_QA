def keep_only_narrative(text: str) -> str:
    """Оставляет из ответа модели только описание дефекта и вывод о релизе.

    Модель часто игнорирует просьбу «напиши только два раздела» и заново
    пересказывает сводку с таблицей. Вместо того чтобы надеяться на её
    дисциплину, вырезаем нужное кодом.
    """
    # Отрезаем всё, что модель написала до раздела про дефект
    start = re.search(r"#+\s*(Описание дефекта|Дефект)", text)
    if start:
        text = text[start.start():]

    # Выбрасываем строки таблицы результатов, если модель их всё-таки вставила
    text = re.sub(r"^\|.*\|\s*$", "", text, flags=re.M)
    # Выбрасываем повторную сводку
    text = re.sub(r"^#+\s*Сводка.*$", "", text, flags=re.M)
    text = re.sub(r"^-\s*(Всего тест-кейсов|Пройдено|Не пройдено).*$", "",
                  text, flags=re.M)

    return re.sub(r"\n{3,}", "\n\n", text).strip()


def make_report(test_cases_md: str) -> str:
    """Отчёт о прогоне: один кейс упал, остальные прошли.

    Таблицу с результатами строит код по реально сгенерированным кейсам —
    так в отчёте не появится выдуманный тест-кейс или неверная цифра.
    """
    # Достаём заголовки кейсов из того, что сгенерировала нейросеть
    found = re.findall(r"##\s*(TC-\d+)\s*[—\-–]\s*(.+)", test_cases_md)
    if not found:
        found = [("TC-001", "Первый кейс"), ("TC-002", "Второй кейс"),
                 ("TC-003", "Третий кейс")]

    # По условию задания: один кейс не прошёл, остальные прошли
    failed_index = 1 if len(found) > 1 else 0
    rows = []
    for i, (case_id, title) in enumerate(found):
        status = "FAILED" if i == failed_index else "PASSED"
        rows.append(f"| {case_id} | {title.strip()} | {status} |")

    passed = len(found) - 1
    failed_id, failed_title = found[failed_index]

    facts = "\n".join([
        "# Отчёт о тестировании",
        "",
        f"Страница: {PAGE_URL}",
        "",
        "## Сводка",
        "",
        f"- Всего тест-кейсов: {len(found)}",
        f"- Пройдено: {passed}",
        "- Не пройдено: 1",
        "",
        "## Результаты",
        "",
        "| ID | Тест-кейс | Статус |",
        "|---|---|---|",
        *rows,
        "",
    ])

    passed_ids = [case_id for i, (case_id, _) in enumerate(found)
                  if i != failed_index]

    narrative = ask_ollama(
        task=(
            "Напиши ДВА раздела отчёта о тестировании и больше ничего:\n\n"
            "## Описание дефекта\n"
            "## Вывод о релизе\n\n"
            f"Не прошёл ТОЛЬКО кейс {failed_id} «{failed_title.strip()}».\n"
            f"Кейсы {', '.join(passed_ids)} прошли успешно — у них дефектов НЕТ, "
            "не описывай их.\n\n"
            "В разделе «Описание дефекта» укажи по одному дефекту "
            f"(только по {failed_id}): что ожидалось, что получилось "
            "фактически, серьёзность (Major).\n"
            "В разделе «Вывод о релизе» напиши, что релиз возможен только "
            "с оговорками из-за незакрытого дефекта.\n\n"
            "НЕ повторяй сводку и таблицу результатов — они уже есть выше "
            "в отчёте."
        ),
        context=f"Тест-кейсы прогона:\n{test_cases_md}",
    )

    return facts + "\n" + keep_only_narrative(narrative)


