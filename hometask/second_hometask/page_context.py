"""Фактическое описание тестируемой страницы.

Единственный источник контекста для генерации документации. Всё перечисленное
проверено на живой странице — модель не должна придумывать элементы, которых
здесь нет: качество документации на ~70% определяется качеством входа.
"""

PAGE_URL = "https://otus.ru/catalog/courses?categories=programming"

# Заголовок генерируется из состояния фильтров (проверено на живой странице)
PAGE_TITLE = (
    "Обучение всех типов по направлению программирование любого уровня "
    "продолжительностью от 0 до 15 месяцев"
)

FILTERS = {
    "Направление": [
        "Все направления", "Программирование", "Архитектура", "Data Science",
        "Инфраструктура", "GameDev", "Безопасность", "Управление",
        "Аналитика и анализ", "Бизнес и продукт в IT", "Импортозамещение",
        "Тестирование", "Нейросети", "IT без программирования",
        "Корпоративные курсы",
    ],
    "Уровень": ["Любой уровень", "Basic", "Professional", "Advanced"],
    "Тип обучения": [
        "Все типы", "Курсы", "Специализации", "Подготовительные курсы",
    ],
    "Продолжительность": ["слайдер от 0 до 15 месяцев"],
}

CONTROLS = [
    "Кнопка «Очистить фильтры»",
    "Кнопка «Показать еще 20» — догружает карточки без перезагрузки страницы",
    "Поле «Поиск» в блоке «Каталог»",
    "Ссылка «Свернуть» — сворачивает длинный список направлений",
]

CARD_FIELDS = [
    "Тип: «Курс» или «Специализация»",
    "Бейдж: «Успеть!» или «Скидка N ₽» (может отсутствовать)",
    "Название курса",
    "Дата старта и продолжительность, формат «30 июня, 2026 · 3 месяца»",
]

# Реальные примеры карточек с открытой страницы
SAMPLE_CARDS = [
    "Курс · Успеть! · Базовая математика для цифровых профессий · 30 июня, 2026 · 3 месяца",
    "Специализация · Успеть! · Java-разработчик · 29 июля, 2026 · 15 месяцев",
    "Курс · Скидка 15900 ₽ · Разработчик на Spring Framework · 14 августа, 2026 · 5 месяцев",
    "Специализация · Скидка 21000 ₽ · Python-разработчик · 23 августа, 2026 · 10 месяцев",
]

NOTABLE_BEHAVIOUR = [
    "Фильтр «Программирование» задаётся параметром URL ?categories=programming",
    "При первой загрузке в каталоге показано 10 карточек",
    "Блок «Вам также может быть интересно» содержит курсы ИЗ ДРУГИХ направлений "
    "(например «Руководитель группы тестирования (QA Lead)» — направление "
    "«Тестирование», «Дизайн сетей ЦОД» — «Инфраструктура»). Это отдельный блок "
    "рекомендаций, он НЕ подчиняется активному фильтру — важно не спутать его "
    "карточки с результатами каталога",
    "Заголовок страницы (title) отражает состояние фильтров",
]


def as_prompt_block() -> str:
    """Контекст страницы в виде текста для промпта модели."""
    lines = [
        f"URL: {PAGE_URL}",
        f"Заголовок страницы: {PAGE_TITLE}",
        "",
        "Фильтры:",
    ]
    for name, values in FILTERS.items():
        lines.append(f"  - {name}: {', '.join(values)}")
    lines.append("")
    lines.append("Управляющие элементы:")
    lines += [f"  - {c}" for c in CONTROLS]
    lines.append("")
    lines.append("Поля карточки курса:")
    lines += [f"  - {f}" for f in CARD_FIELDS]
    lines.append("")
    lines.append("Примеры реальных карточек:")
    lines += [f"  - {c}" for c in SAMPLE_CARDS]
    lines.append("")
    lines.append("Особенности поведения:")
    lines += [f"  - {b}" for b in NOTABLE_BEHAVIOUR]
    return "\n".join(lines)


if __name__ == "__main__":
    print(as_prompt_block())
